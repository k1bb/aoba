"""Dynamic / Accelerated-Equilibrium 2D Ice-Sheet & Vertical Coordinate Remapping Module.

Implements a Shallow Ice Approximation (SIA) continental ice-sheet model on the global SCVT
Voronoi C-grid coupled with:
1. Exponential Moving Average (EMA) smoothing of annual climatic surface mass balance (SMB)
   generated by `step_surface` (snowfall minus melt, sublimation, and bare-ice melt potential).
2. Spinup acceleration factor `alpha_acc` advancing Glen's flow law (`n = 3`) ice flow and
   equilibrium/relaxed bedrock isostasy across `alpha_acc` ice-years per climate year.
3. Conservative vertical coordinate updating (`compute_stf_heights`) and smooth barometric
   column remapping for both host SCVT atmosphere and embedded 3D CRM columns whenever ice-sheet
   growth or deglaciation alters surface topography `z_topo`.

References
----------
- Vialov (1958) & Cuffey & Paterson (2010, The Physics of Glaciers): Glen's flow law (`n = 3`)
  Shallow Ice Approximation (SIA) nonlinear diffusion on continental ice caps.
- Mahaffy (1976, J. Geophys. Res., 81, 1059-1066) & Bueler et al. (2005): Upstream Type-I
  finite-volume ice diffusivity ensuring non-negative thickness and exact volume conservation.
- Pollard & DeConto (2012, Geosci. Model Dev., 5) & Le Meur & Huybrechts (1996): Relaxed
  lithospheric isostasy (`rho_ice / rho_mantle ~ 0.278`) and asynchronous climate acceleration.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
import torch

from aoba import constants as C
from aoba.scvt_dynamics import GlobalAtmosState, compute_scvt_divergence
from aoba.scvt_mesh import SCVTMesh
from aoba.thermodynamics import diagnose_pressure_temperature
from aoba.vertical_grid import VerticalGrid, compute_stf_heights


RHO_ICE: float = 917.0                              # Solid glacial ice density [kg m^-3]
RHO_MANTLE: float = 3300.0                          # Upper-mantle lithospheric density [kg m^-3]
ISOSTASY_RATIO: float = RHO_ICE / RHO_MANTLE        # Equilibrium bedrock depression ratio [-]
SECONDS_PER_YEAR: float = C.DAYS_PER_YEAR * C.SECONDS_PER_DAY
A_GLEN_PER_YEAR: float = 1.0e-16                   # Temperate/polythermal Glen flow softness [Pa^-3 yr^-1]
A_GLEN_PER_SEC: float = A_GLEN_PER_YEAR / SECONDS_PER_YEAR  # [Pa^-3 s^-1]
GAMMA_SIA: float = 0.4 * A_GLEN_PER_SEC * ((RHO_ICE * C.GRAVITY) ** 3)  # SIA flux prefactor [m^-3 s^-1]
H_ICE_THRESHOLD_M: float = 5.0                      # Minimum grounded ice thickness to classify as IceSheet [m]
H_ICE_MAX_M: float = 6000.0                         # Physical upper bound on continental ice thickness [m]


def recompute_derived_constants() -> None:
    """Refresh SIA flow prefactor and isostasy ratio after constant updates."""
    global ISOSTASY_RATIO, SECONDS_PER_YEAR, A_GLEN_PER_SEC, GAMMA_SIA
    ISOSTASY_RATIO = RHO_ICE / RHO_MANTLE
    SECONDS_PER_YEAR = C.DAYS_PER_YEAR * C.SECONDS_PER_DAY
    A_GLEN_PER_SEC = A_GLEN_PER_YEAR / SECONDS_PER_YEAR
    GAMMA_SIA = 0.4 * A_GLEN_PER_SEC * ((RHO_ICE * C.GRAVITY) ** 3)


@dataclass
class IceSheetState:
    """Prognostic 2D continental ice thickness, isostatic bedrock, & EMA mass-balance state `[n_cells]`."""

    h_ice: torch.Tensor               # Continental ice-sheet thickness H [n_cells] [m]
    z_bed: torch.Tensor               # Current subglacial bedrock elevation b [n_cells] [m]
    z_bed_unloaded: torch.Tensor      # Isostatically rebounded unloaded bedrock b_0 [n_cells] [m]
    smb_ema_kgm2_s: torch.Tensor      # EMA-filtered climatic surface mass balance [n_cells] [kg m^-2 s^-1]
    smb_year_accum_kgm2: torch.Tensor # Running annual accumulated SMB [n_cells] [kg m^-2]
    year_elapsed_sec: float = 0.0     # Accumulated climate time in current SMB year [s]
    n_updates: int = 0                # Number of completed ice-sheet update cycles


def init_icesheet_state(mesh: SCVTMesh) -> IceSheetState:
    """Initialize prognostic 2D `IceSheetState` cleanly matching `mesh.z_topo` at `t = 0`."""
    is_ocean = mesh.ocean_frac >= 0.5
    h0 = (
        torch.where(is_ocean, torch.zeros_like(mesh.z_topo), torch.clamp(mesh.h_ice_init, min=0.0))
        if mesh.h_ice_init is not None
        else torch.zeros_like(mesh.z_topo)
    )
    # Anchor z_bed = z_topo - h0 on terrestrial cells so initial z_bed + h0 equals mesh.z_topo exactly
    zb_terr = mesh.z_topo - h0
    zb = torch.where(is_ocean, mesh.z_bed if mesh.z_bed is not None else zb_terr, zb_terr)
    zb_unloaded = zb + ISOSTASY_RATIO * h0

    return IceSheetState(
        h_ice=h0,
        z_bed=zb,
        z_bed_unloaded=zb_unloaded,
        smb_ema_kgm2_s=torch.zeros_like(h0),
        smb_year_accum_kgm2=torch.zeros_like(h0),
        year_elapsed_sec=0.0,
        n_updates=0,
    )


def smooth_scvt_terrain_torch(mesh: SCVTMesh, z_topo: torch.Tensor, n_pass: int = 2) -> torch.Tensor:
    """Apply Klemp (2011) 2-pass conservative neighbor Laplacian smoothing on the SCVT Voronoi mesh."""
    is_ocean = mesh.ocean_frac >= 0.5
    c0 = mesh.cells_on_edge[:, 0]
    c1 = mesh.cells_on_edge[:, 1]
    e_cell = mesh.edges_on_cell
    active = (mesh.edge_sign_on_cell != 0.0).to(z_topo.dtype)
    deg = torch.clamp(active.sum(dim=-1), min=1.0)

    z_s = torch.where(is_ocean, torch.zeros_like(z_topo), z_topo)
    cell_idx = torch.arange(mesh.n_cells, device=z_topo.device, dtype=torch.int64).unsqueeze(-1)
    nb_c0 = c0[e_cell]
    nb_c1 = c1[e_cell]
    nb_idx = torch.where(nb_c0 == cell_idx, nb_c1, nb_c0)

    for _ in range(n_pass):
        nb_mean = (z_s[nb_idx] * active).sum(dim=-1) / deg
        z_next = 0.75 * z_s + 0.25 * nb_mean
        z_s = torch.where(is_ocean, torch.zeros_like(z_s), z_next)
    return z_s


def step_sia_icesheet_scvt(
    ice: IceSheetState,
    mesh: SCVTMesh,
    ema_years: float = 5.0,
    accel_factor: float = 100.0,
    isostasy_tau_yr: float = 1000.0,
    smb_override_kgm2_s: torch.Tensor | None = None,
) -> dict[str, torch.Tensor | float]:
    """Update EMA SMB, integrate 2D SIA Glen ice flow & relaxed isostasy, and reset annual SMB bucket."""
    dt_clim_sec = max(ice.year_elapsed_sec, 1.0)
    dt_clim_yr = dt_clim_sec / SECONDS_PER_YEAR

    if smb_override_kgm2_s is not None:
        smb_yr_rate = smb_override_kgm2_s
    else:
        smb_yr_rate = ice.smb_year_accum_kgm2 / dt_clim_sec

    if ice.n_updates == 0 or ema_years <= 0.0:
        ice.smb_ema_kgm2_s = smb_yr_rate.clone()
    else:
        alpha_ema = 1.0 - math.exp(-dt_clim_yr / max(ema_years, 1.0e-3))
        ice.smb_ema_kgm2_s = (1.0 - alpha_ema) * ice.smb_ema_kgm2_s + alpha_ema * smb_yr_rate

    is_ocean = mesh.ocean_frac >= 0.5
    is_terr = ~is_ocean
    dt_ice_yr = dt_clim_yr * max(accel_factor, 0.0)
    dt_ice_sec = dt_ice_yr * SECONDS_PER_YEAR

    calved_vol_m3 = torch.zeros((), device=ice.h_ice.device, dtype=ice.h_ice.dtype)
    if dt_ice_sec > 0.0:
        c0 = mesh.cells_on_edge[:, 0]
        c1 = mesh.cells_on_edge[:, 1]
        dc_e = mesh.dc_edge
        dx_min = float(dc_e.min().item())

        b_ice = torch.where(is_terr, ice.smb_ema_kgm2_s / RHO_ICE, torch.zeros_like(ice.h_ice))
        h = torch.where(is_ocean, torch.zeros_like(ice.h_ice), ice.h_ice)

        # Estimate initial diffusivity to choose stable explicit substeps
        s0 = torch.where(is_ocean, torch.zeros_like(h), ice.z_bed + h)
        slope0 = torch.abs(s0[c1] - s0[c0]) / dc_e
        h_up0 = torch.where(s0[c0] >= s0[c1], h[c0], h[c1])
        d_est = GAMMA_SIA * (h_up0 ** 5) * (slope0 ** 2)
        d_max = float(d_est.max().item()) if d_est.numel() > 0 else 0.0
        n_sub = min(max(int(math.ceil(dt_ice_sec * d_max / max(0.12 * dx_min * dx_min, 1.0))), 1), 256)
        dt_sub = dt_ice_sec / float(n_sub)
        d_cap = 0.12 * dx_min * dx_min / max(dt_sub, 1.0)

        for _ in range(n_sub):
            s = torch.where(is_ocean, torch.zeros_like(h), ice.z_bed + h)
            ds_dx = (s[c1] - s[c0]) / dc_e
            h_up = torch.where(s[c0] >= s[c1], h[c0], h[c1])
            d_e = torch.clamp(GAMMA_SIA * (h_up ** 5) * (ds_dx * ds_dx), max=d_cap)
            flux_e = -d_e * ds_dx
            dh_dyn_dt = -compute_scvt_divergence(mesh, flux_e)
            h_next = torch.clamp(h + dt_sub * (dh_dyn_dt + b_ice), 0.0, H_ICE_MAX_M)
            calved_vol_m3 = calved_vol_m3 + (mesh.area_cell * torch.where(is_ocean, h_next, torch.zeros_like(h_next))).sum()
            h = torch.where(is_ocean, torch.zeros_like(h_next), h_next)

        ice.h_ice = h

        # Relax subglacial bedrock toward equilibrium isostasy
        zb_eq = ice.z_bed_unloaded - ISOSTASY_RATIO * ice.h_ice
        if isostasy_tau_yr <= 0.0:
            ice.z_bed = torch.where(is_terr, zb_eq, ice.z_bed)
        else:
            alpha_iso = 1.0 - math.exp(-dt_ice_yr / isostasy_tau_yr)
            ice.z_bed = torch.where(is_terr, ice.z_bed + alpha_iso * (zb_eq - ice.z_bed), ice.z_bed)

    ice.smb_year_accum_kgm2.zero_()
    ice.year_elapsed_sec = 0.0
    ice.n_updates += 1

    z_topo_new = torch.where(is_ocean, torch.zeros_like(ice.h_ice), ice.z_bed + ice.h_ice)
    z_smooth_new = smooth_scvt_terrain_torch(mesh, z_topo_new)
    ice_area_mkm2 = float(((mesh.area_cell * (ice.h_ice >= H_ICE_THRESHOLD_M).to(ice.h_ice.dtype)).sum() * 1.0e-12).item())

    return {
        "z_topo_new": z_topo_new,
        "z_topo_smooth_new": z_smooth_new,
        "calved_vol_m3": float(calved_vol_m3.item()),
        "ice_area_mkm2": ice_area_mkm2,
        "ice_vol_1e6km3": float(((mesh.area_cell * ice.h_ice).sum() * 1.0e-15).item()),
    }


def _interp_vertical_1d(z_src: torch.Tensor, vals: torch.Tensor, z_dst: torch.Tensor) -> torch.Tensor:
    """Piecewise-linear column interpolation `[nz, nc, ...]` with clamped boundary extrapolation."""
    nz_s, nc = z_src.shape
    nz_d = z_dst.shape[0]
    trailing = vals.shape[2:]
    flat_v = vals.reshape(nz_s, nc, -1)
    n_tr = flat_v.shape[-1]

    zq = torch.clamp(z_dst, min=z_src[0:1], max=z_src[-1:])
    # Count source interfaces <= zq to locate lower bracket j in [0, nz_s - 2]
    idx_lo = torch.clamp((z_src.unsqueeze(0) <= zq.unsqueeze(1)).to(torch.int64).sum(dim=1) - 1, 0, nz_s - 2)
    idx_hi = idx_lo + 1

    col_idx = torch.arange(nc, device=z_src.device, dtype=torch.int64).unsqueeze(0).expand(nz_d, nc)
    z0 = z_src[idx_lo, col_idx]
    z1 = z_src[idx_hi, col_idx]
    w = torch.clamp((zq - z0) / torch.clamp(z1 - z0, min=1.0e-6), 0.0, 1.0).unsqueeze(-1)

    v0 = flat_v[idx_lo, col_idx]  # [nz_d, nc, n_tr]
    v1 = flat_v[idx_hi, col_idx]
    out = (1.0 - w) * v0 + w * v1
    return out.reshape((nz_d, nc) + trailing)


def _remap_thermo_state(
    z_c_old: torch.Tensor,
    z_c_new: torch.Tensor,
    rho_d: torch.Tensor,
    theta_m: torch.Tensor,
    q_n: torch.Tensor,
    q_p: torch.Tensor,
    q_v: torch.Tensor,
    q_c: torch.Tensor,
    q_i: torch.Tensor,
) -> tuple[torch.Tensor, ...]:
    """Interpolate thermo/moisture fields onto `z_c_new` with barometric below-surface continuity."""
    pres_old, _, _ = diagnose_pressure_temperature(rho_d, theta_m, q_v)
    lnp_new = _interp_vertical_1d(z_c_old, torch.log(torch.clamp(pres_old, min=1.0)), z_c_new)
    thm_new = _interp_vertical_1d(z_c_old, theta_m, z_c_new)
    qn_new = torch.clamp(_interp_vertical_1d(z_c_old, q_n, z_c_new), min=0.0)
    qp_new = torch.clamp(_interp_vertical_1d(z_c_old, q_p, z_c_new), min=0.0)
    qv_new = torch.clamp(_interp_vertical_1d(z_c_old, q_v, z_c_new), min=0.0)
    qc_new = torch.clamp(_interp_vertical_1d(z_c_old, q_c, z_c_new), min=0.0)
    qi_new = torch.clamp(_interp_vertical_1d(z_c_old, q_i, z_c_new), min=0.0)

    below_old = z_c_new < z_c_old[0:1]
    if below_old.any():
        extra_dims = (1,) * (pres_old.ndim - below_old.ndim)
        below_mask = below_old.view(below_old.shape + extra_dims)
        dz_raw = (z_c_new - z_c_old[0:1]).view(below_old.shape + extra_dims)
        exner0 = torch.pow(pres_old[0:1] / C.P_REF, C.KAPPA_D)
        p_extrap = pres_old[0:1] * torch.pow(
            torch.clamp(1.0 - (C.GRAVITY * dz_raw) / (C.CP_D * theta_m[0:1] * exner0), min=0.2, max=2.5),
            1.0 / C.KAPPA_D,
        )
        pres_new = torch.where(below_mask, p_extrap, torch.exp(lnp_new))
    else:
        pres_new = torch.exp(lnp_new)

    exner_new = torch.pow(pres_new / C.P_REF, C.KAPPA_D)
    rho_new = torch.clamp(pres_new / (C.R_D * thm_new * exner_new), min=1.0e-5)
    return rho_new, thm_new, qn_new, qp_new, qv_new, qc_new, qi_new


def remap_atmosphere_and_crm_vertical(
    atmos: GlobalAtmosState,
    crm,
    mesh: SCVTMesh,
    vgrid: VerticalGrid,
    z_topo_smooth_new: torch.Tensor,
) -> bool:
    """Update Klemp STF vertical grid to `z_topo_smooth_new` and barometrically remap `atmos` & `crm`."""
    dz_surf = torch.abs(z_topo_smooth_new - atmos.z_w[0]).max()
    if float(dz_surf.item()) < 0.05:
        return False

    z_w_new, z_c_new, dz_c_new = compute_stf_heights(vgrid, z_topo_smooth_new)
    z_c_old = atmos.z_c

    (
        atmos.rho_d, atmos.theta_m, atmos.q_n, atmos.q_p, atmos.q_v, atmos.q_c, atmos.q_i,
    ) = _remap_thermo_state(z_c_old, z_c_new, atmos.rho_d, atmos.theta_m, atmos.q_n, atmos.q_p, atmos.q_v, atmos.q_c, atmos.q_i)

    c0, c1 = mesh.cells_on_edge[:, 0], mesh.cells_on_edge[:, 1]
    atmos.u_edge = _interp_vertical_1d(0.5 * (z_c_old[:, c0] + z_c_old[:, c1]), atmos.u_edge, 0.5 * (z_c_new[:, c0] + z_c_new[:, c1]))
    atmos.w = torch.zeros_like(atmos.w)
    atmos.z_w = z_w_new
    atmos.z_c = z_c_new
    atmos.dz_c = dz_c_new

    if crm is not None:
        (
            crm.rho_d, crm.theta_m, crm.q_n, crm.q_p, crm.q_v, crm.q_c, crm.q_i,
        ) = _remap_thermo_state(z_c_old, z_c_new, crm.rho_d, crm.theta_m, crm.q_n, crm.q_p, crm.q_v, crm.q_c, crm.q_i)
        crm.u = _interp_vertical_1d(z_c_old, crm.u, z_c_new)
        crm.v = _interp_vertical_1d(z_c_old, crm.v, z_c_new)
        crm.qke = torch.clamp(_interp_vertical_1d(z_c_old, crm.qke, z_c_new), min=1.0e-6)
        crm.w = torch.zeros_like(crm.w)

    return True
